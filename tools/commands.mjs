#!/usr/bin/env node
// Generate docs/COMMANDS.md from the same tables the game runs.
//
// Usage: node tools/commands.mjs --write|--check
//
// The check fails if the committed file differs from the generated one, so a
// verb cannot exist without appearing in the reference.

import { readFileSync, writeFileSync } from "node:fs";
import { loadVerbs } from "../runtime/verbs.mjs";
import { loadChannels } from "../runtime/channels.mjs";
import { loadSocials } from "../runtime/socials.mjs";
import { loadQuests } from "../runtime/quests.mjs";
import { loadWorld } from "../runtime/worlddata.mjs";

const OUT = "docs/COMMANDS.md";

function render() {
  const verbs = loadVerbs().verbs;
  const channels = loadChannels().channels;
  const socials = loadSocials().socials;
  const quests = loadQuests().quests;
  const world = loadWorld({ mode: "single" });

  const lines = [];
  const add = (line = "") => lines.push(line);
  add("<!-- @generated by node tools/commands.mjs --write from world/data. Do not edit. -->");
  add();
  add("# Commands");
  add();
  add("Generated from `world/data/verbs.json`, `channels.json`, `socials.json`,");
  add("`quests.json` and `world.json`. `node tools/commands.mjs --check` fails if this");
  add("file is stale.");
  add();
  add("## Movement and sight");
  add();
  add("`north`, `south`, `east`, `west`, `up`, `down` (or `n/s/e/w/u/d`).");
  add("`look` shows the room; `look <thing>` and `examine <thing>` show a detail, an");
  add("object or a mobile. `who` lists the room; `awake` lists everyone online.");
  add();
  add("## Verbs");
  add();
  add("| Verb | Aliases | Argument |");
  add("| --- | --- | --- |");
  for (const name of Object.keys(verbs).sort()) {
    const entry = verbs[name] ?? {};
    add(`| \`${name}\` | ${(entry.aliases ?? []).map((alias) => `\`${alias}\``).join(", ") || "—"} | ${entry.argument ?? "none"} |`);
  }
  add();
  add("## Channels");
  add();
  add("| Channel | Aliases | Minimum role |");
  add("| --- | --- | --- |");
  for (const channel of channels) {
    add(`| \`${channel.name}\` | ${(channel.aliases ?? []).map((alias) => `\`${alias}\``).join(", ") || "—"} | ${channel.minRole} |`);
  }
  add();
  add("## Socials");
  add();
  add("| Social | Aliases |");
  add("| --- | --- |");
  for (const name of Object.keys(socials).sort()) {
    add(`| \`${name}\` | ${(socials[name].aliases ?? []).map((alias) => `\`${alias}\``).join(", ") || "—"} |`);
  }
  add();
  add("## Quests");
  add();
  add("| Quest | Name | Level | Objectives | Reward |");
  add("| --- | --- | --- | --- | --- |");
  for (const quest of quests) {
    const objectives = (quest.objectives ?? []).map((objective) => objective.text ?? objective.kind).join("; ");
    add(`| \`${quest.id}\` | ${quest.name} | ${quest.level} | ${objectives} | ${quest.rewards?.xp ?? 0} xp |`);
  }
  add();
  add("## Rooms");
  add();
  add("| Id | Room | Zone | Safe | Exits |");
  add("| --- | --- | --- | --- | --- |");
  for (const [id, room] of Object.entries(world.rooms)) {
    const exits = Object.entries(room.exits ?? {}).map(([dir, to]) => `${dir} ${to}`).join(", ") || "none";
    add(`| ${id} | ${room.name} | ${room.zone ?? "—"} | ${room.safe ? "yes" : "no"} | ${exits} |`);
  }
  add();
  return `${lines.join("\n")}\n`;
}

const text = render();
if (process.argv.includes("--write")) {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
} else if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch {}
  if (current !== text) {
    console.error(`${OUT} is stale; run node tools/commands.mjs --write`);
    process.exit(1);
  }
  console.log(`${OUT} is current`);
} else {
  process.stdout.write(text);
}
