#!/usr/bin/env node
// The claims ledger: what this project says, at what honesty level, with what
// evidence. A build claim names the gate; an open claim names a query, a sample
// size and a seed; a some-true claim names its authority.
//
// Usage: node tools/claims.mjs --write|--check|--list
//
// The generated docs/CLAIMS.md is committed, so a claim cannot exist only in
// prose and a level cannot be quietly raised.

import { existsSync, readFileSync, writeFileSync } from "node:fs";

const LEDGER = "claims/ledger.json";
const OUT = "docs/CLAIMS.md";
const LEVELS = new Set(["build", "open", "some-true"]);

const ledger = JSON.parse(readFileSync(LEDGER, "utf8"));
const errors = [];
const seen = new Set();
for (const claim of ledger.claims ?? []) {
  if (!claim.id) errors.push("a claim has no id");
  if (seen.has(claim.id)) errors.push(`claim ${claim.id} is used twice`);
  seen.add(claim.id);
  if (!LEVELS.has(claim.level)) errors.push(`claim ${claim.id} has unknown level ${claim.level}`);
  if (typeof claim.statement !== "string" || claim.statement.length < 10) errors.push(`claim ${claim.id} has no statement`);
  if (claim.level === "build" && (!claim.gate || !existsSync(claim.gate))) errors.push(`build claim ${claim.id} names no gate file`);
  if (claim.level === "open") {
    if (!claim.query || !existsSync(claim.query)) errors.push(`open claim ${claim.id} names no query file`);
    if (!Number.isInteger(claim.sample_size) || claim.sample_size < 1) errors.push(`open claim ${claim.id} has no sample size`);
    if (typeof claim.seed !== "string" || !claim.seed.trim()) errors.push(`open claim ${claim.id} has no seed`);
  }
  if (claim.level === "some-true" && (typeof claim.authority !== "string" || !claim.authority.trim())) {
    errors.push(`some-true claim ${claim.id} names no authority`);
  }
}

function render() {
  const lines = [];
  const add = (line = "") => lines.push(line);
  add("<!-- @generated by node tools/claims.mjs --write from claims/ledger.json. Do not edit. -->");
  add();
  add("# Claims");
  add();
  add("What this project says, at what honesty level, with what evidence. A");
  add("`build` claim names the gate that proves it here. An `open` claim is measured");
  add("and reported, never asserted; it names its query, sample size and seed. A");
  add("`some-true` claim reproduces a named authority.");
  add();
  add("| Id | Level | Claim | Evidence |");
  add("| --- | --- | --- | --- |");
  for (const claim of ledger.claims ?? []) {
    const evidence = claim.level === "build"
      ? `\`${claim.gate}\``
      : claim.level === "open"
        ? `\`${claim.query}\`; n=${claim.sample_size}; seed: ${claim.seed}`
        : claim.authority;
    add(`| ${claim.id} | ${claim.level} | ${claim.statement} | ${evidence} |`);
  }
  add();
  return `${lines.join("\n")}\n`;
}

if (process.argv.includes("--write")) {
  writeFileSync(OUT, render());
  console.log(`wrote ${OUT}`);
} else if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(OUT, "utf8"); } catch {}
  if (current !== render()) {
    console.error(`${OUT} is stale; run node tools/claims.mjs --write`);
    process.exit(1);
  }
  if (errors.length) {
    console.error("claims are invalid:");
    for (const error of errors) console.error(`  - ${error}`);
    process.exit(1);
  }
  console.log(`${OUT} is current`);
} else if (process.argv.includes("--list")) {
  for (const claim of ledger.claims ?? []) console.log(`${claim.id}\t${claim.level}\t${claim.statement}`);
} else {
  process.stdout.write(render());
}
